#!/usr/bin/env python3
"""Generate Appendix I, the deck key reference, from snapy's YAML parsers at the code pin.

Every block of a deck that snapy reads is guarded by a `check_keys(node, "<path>", {keys...})` call
(src/input/check_keys.hpp), which refuses any key not in its list. Those lists are the inventory: one row per
accepted key, with the default the parser falls back to when the key is absent, the line that reads it, and the
section of the book that explains it. The keys a list hands to another library (`"kintera"`, `"pyharp"`) are
listed too, with that library as their reader and no default (their defaults are not in snapy's source).

The default is taken from the parser, in this order: a `["key"].as<T>(fallback)` read; a helper called with the
key and a fallback (`read_finite("key", 1.0)`) or a helper that returns a constant when the key is absent; a
check that the key is present (required); a read guarded by `if (node["key"])`, whose options-struct default
(`ADD_ARG(T, member) = value`) is kept when the key is absent. A key whose value is itself a checked block is a
block. Anything else is reported as found by none of these rules; nothing is guessed.

A key links to a section of the book when a labelled `##` section of chapters 1 to 16, or of appendices D and E,
names it in inline code: by its path (`dynamics/wb-wall-clamp`, `const-gravity/gravity-work`), or by the key and
its enclosing block in the same section (or anywhere, for a distinctive name no other block accepts), and keys of
the section's fenced YAML examples count by their paths. Path matches win, then the section that
tools/reader-glossary.json names as the key's definition, then the most mentions, then book order. A key no
section names is marked "no section"; the page gives no explanation of its own.

    python3 tools/gen_deck_keys.py --refresh [<snapy checkout>]  # re-extract tools/deck-keys.json at code_pin.yml
    python3 tools/gen_deck_keys.py                               # rewrite the fragment from the JSON and the book
    python3 tools/gen_deck_keys.py --check                       # exit 1 if the fragment is stale
    python3 tools/gen_deck_keys.py --stats                       # keys, readers, defaults found, sections linked

Only the Python standard library is needed. Exit status 0 on success, 1 on a stale fragment or a problem.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPORT = Path(__file__).resolve().parent.parent
BOOK = REPORT / "book"
DATA = REPORT / "tools" / "deck-keys.json"
FRAGMENT = BOOK / "chapters" / "17-appendices" / "_appi-deck-keys.qmd"
HEADER = ("<!-- GENERATED by tools/gen_deck_keys.py from tools/deck-keys.json and the section texts; do not edit.\n"
          "     refresh the JSON: python3 tools/gen_deck_keys.py --refresh -->")

sys.path.insert(0, str(Path(__file__).resolve().parent))


# --- extraction from the source ---------------------------------------------------------------------------------

_CALL = re.compile(r"\bcheck_keys\s*\(")
_STR = re.compile(r'"((?:[^"\\]|\\.)*)"')


def _balanced(text: str, i: int) -> int:
    """Index just past the parenthesis that closes the one opened at text[i - 1]."""
    depth = 1
    while depth and i < len(text):
        c = text[i]
        if c == '"':
            i = text.index('"', i + 1) + 1
            continue
        depth += {"(": 1, ")": -1}.get(c, 0)
        i += 1
    return i


def _args(inner: str) -> list[str]:
    """Top-level comma-separated arguments of a call (braces and parentheses nest)."""
    out, depth, cur, quote = [], 0, "", False
    for c in inner:
        if c == '"':
            quote = not quote
        elif not quote and c in "({<[":
            depth += 1
        elif not quote and c in ")}>]":
            depth -= 1
        if c == "," and depth == 0 and not quote:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    return out + [cur.strip()] if cur.strip() else out


def _path(expr: str) -> str:
    """`"outputs/" + std::to_string(fid)` -> `outputs/<fid>`: string literals kept, other operands as <name>."""
    parts = []
    for op in expr.split("+"):
        op = op.strip()
        m = re.fullmatch(r'(?:std::string\()?"([^"]*)"\)?', op)
        if m:
            parts.append(m[1])
        else:
            name = re.findall(r"\w+", op)
            parts.append(f"<{name[-1] if name else 'n'}>")
    return "".join(parts)


def _brace_end(text: str, i: int) -> int:
    """Index just past the brace that closes the one at text[i]."""
    depth = 0
    while i < len(text):
        c = text[i]
        if c == '"':
            i = text.index('"', i + 1) + 1
            continue
        depth += {"{": 1, "}": -1}.get(c, 0)
        i += 1
        if depth == 0:
            break
    return i


_SIGNATURE = re.compile(r"^[A-Za-z][^;{}]*?\)\s*(?:const\s*)?\{", re.M)


def _function_body(text: str, pos: int) -> tuple[int, int]:
    """(start, end) of the brace block of the top-level function that contains offset `pos`."""
    starts = [m.end() - 1 for m in _SIGNATURE.finditer(text, 0, pos)]
    start = starts[-1] if starts else 0
    return start, _brace_end(text, start)


def _line(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def _fallback_reads(text: str, node: str, key: str) -> list[tuple[str, int]]:
    """(fallback expression, offset) of every `<node>["key"].as<T>(fallback)` in text; `()` gives no fallback."""
    out = []
    for m in re.finditer(r'(?<![\w\]])%s\["%s"\]\s*\.as<' % (re.escape(node), re.escape(key)), text):
        i, depth = m.end(), 1
        while depth:
            depth += {"<": 1, ">": -1}.get(text[i], 0)
            i += 1
        if text[i] != "(":
            continue
        arg = text[i + 1:_balanced(text, i + 1) - 1].strip()
        if arg:
            out.append((arg, m.start()))
    return out


def _helper_defaults(body: str) -> dict[str, tuple[str, str]]:
    """Helpers of the body that give a key a fallback: name -> ('arg', '') or ('const', value)."""
    out = {}
    for m in re.finditer(r"auto\s+(\w+)\s*=\s*\[&\]\s*\(char const\*\s*key(?:,\s*[\w:]+\s+(\w+))?\)\s*\{", body):
        name, param = m[1], m[2]
        block = body[m.end() - 1:_brace_end(body, m.end() - 1)]
        if param and re.search(r"return\s+%s\s*;" % param, block):
            out[name] = ("arg", "")
            continue
        r = re.search(r"if\s*\(\s*!\s*\w+\[key\]\s*\)\s*return\s+([^;]+);", block)
        if r:
            out[name] = ("const", r[1].strip())
    return out


def _add_arg_defaults(tree: Path) -> dict[str, list[tuple[str, str, int]]]:
    """member -> [(value, header path, line)] for every `ADD_ARG(T, member) = value;` under src/."""
    out: dict[str, list] = {}
    for h in sorted((tree / "src").rglob("*.hpp")):
        text = h.read_text(errors="replace")
        for m in re.finditer(r"ADD_ARG\(\s*(.+?),\s*(\w+)\)\s*=\s*([^;]+);", text):
            out.setdefault(m[2], []).append((m[3].strip(), h.relative_to(tree).as_posix(), _line(text, m.start())))
    return out


_READER = re.compile(r"\b(\w+)::from_yaml\(\s*(?:const\s+)?YAML::Node\s*(?:const\s*)?&\s*(\w+)\)\s*\{")


def _readers(texts) -> dict[str, list[tuple[str, str, int, int, str]]]:
    """Class -> [(file, text, body start, body end, node parameter)] of every `X::from_yaml(YAML::Node ...)`."""
    out: dict[str, list] = {}
    for rel, text in texts:
        for m in _READER.finditer(text):
            out.setdefault(m[1], []).append((rel, text, m.end() - 1, _brace_end(text, m.end() - 1), m[2]))
    return out


def _default(key, node, body, body_off, text, rel, ctx, depth=0) -> dict:
    """The default of one key of the block `node` (a C++ expression) in one parser body (module docstring)."""
    members, texts, readers, parent = ctx
    k = re.escape(key)
    n = r"(?<![\w\]])" + re.escape(node)

    def at(off):
        return _line(text, body_off + off)

    hits = _fallback_reads(body, node, key)
    if hits:
        arg, off = hits[0]
        return {"kind": "fallback", "value": arg, "file": rel, "line": at(off)}
    for name, (how, value) in _helper_defaults(body).items():
        m = re.search(r'\b%s\("%s"(?:,\s*([^)]+))?\)' % (name, k), body)
        if m:
            val = m[1].strip() if how == "arg" and m[1] else value
            return {"kind": "fallback", "value": val, "file": rel, "line": at(m.start())}
    m = re.search(r'TORCH_CHECK\(\s*%s\["%s"\]\s*,\s*"[^"]*required' % (n, k), body)
    if m:
        return {"kind": "required", "value": "", "file": rel, "line": at(m.start())}
    m = re.search(r'for\s*\([^:;]+:\s*%s\["%s"\]\s*\)' % (n, k), body)
    if m:
        return {"kind": "map", "value": "", "file": rel, "line": at(m.start())}
    m = re.search(r'%s\["%s"\]\s*\?' % (n, k), body)
    if m:
        return {"kind": "guarded", "value": "", "file": rel, "line": at(m.start())}
    m = re.search(r'if\s*\(\s*%s\["%s"\]\s*\)\s*\{?' % (n, k), body)
    if m:
        tail = body[m.end():m.end() + 600]
        e = re.search(r"else\s*\{[^}]*?(?:throw|TORCH_CHECK\(false)[^;]*?(?:must be specified|required)", tail)
        if e and "if (" not in tail[:e.start()]:
            return {"kind": "required", "value": "", "file": rel, "line": at(m.start())}
        brace = body.find("{", m.end() - 1, m.end() + 1)
        block = body[brace:_brace_end(body, brace)] if brace >= 0 else tail.split(";", 1)[0]
        a = re.search(r"->(\w+)\(\)\s*=", block)
        if a and a[1] in members and len({v for v, *_ in members[a[1]]}) == 1:
            value, hpath, hline = members[a[1]][0]
            return {"kind": "struct", "value": value, "file": hpath, "line": hline}
        return {"kind": "guarded", "value": "", "file": rel, "line": at(m.start())}
    # the block handed whole to another reader: `[X::]from_yaml(<node>)`
    for m in re.finditer(r"(?:\b(\w+)::)?from_yaml\(\s*%s\s*\)" % re.escape(node), body):
        cands = [r for c, rs in readers.items() for r in rs if (c == m[1] if m[1] else r[0] == rel)]
        if len(cands) == 1 and depth < 2:
            frel, ftext, s0, s1, param = cands[0]
            d = _default(key, param, ftext[s0:s1], s0, ftext, frel, ctx, depth + 1)
            if d["kind"] != "none":
                return d
    # read elsewhere in the source as `["<parent>"]["key"].as<T>(fallback)`, with one value only
    found = {(arg, f, _line(t, off)) for f, t in texts for arg, off in _fallback_reads(t, f'["{parent}"]', key)}
    found |= {(arg, f, _line(t, off)) for f, t in texts for arg, off in _fallback_reads(t, f'"{parent}"]', key)}
    if len({a for a, *_ in found}) == 1:
        arg, f, ln = sorted(found)[0]
        return {"kind": "fallback", "value": arg, "file": f, "line": ln}
    if body.count(f'"{key}"') == 1:  # named only in the check_keys list
        return {"kind": "unread", "value": "", "file": rel, "line": 0}
    return {"kind": "none", "value": "", "file": rel, "line": 0}


def _matches(pattern: str, path: str) -> bool:
    """`dynamics/reconstruct/<section>` matches `dynamics/reconstruct/vertical`."""
    a, b = pattern.split("/"), path.split("/")
    return len(a) == len(b) and all(x == y or x.startswith("<") for x, y in zip(a, b))


def extract(tree: Path) -> list[dict]:
    """One record per (block path, key) accepted by a check_keys call under src/."""
    files = sorted(p for p in (tree / "src").rglob("*.cpp") if p.relative_to(tree).parts[:2] != ("src", "input"))
    texts = [(p.relative_to(tree).as_posix(), p.read_text(errors="replace")) for p in files]
    members = _add_arg_defaults(tree)
    readers = _readers(texts)
    calls = []
    for rel, text in texts:
        for m in _CALL.finditer(text):
            end = _balanced(text, m.end())
            args = _args(text[m.end():end - 1])
            if len(args) < 3:
                continue
            calls.append((rel, text, m.start(), _path(args[1]), args))
    paths = {c[3] for c in calls}
    rows = []
    for rel, text, pos, path, args in calls:
        start, end = _function_body(text, pos)
        body = text[start:end]
        parent = [s for s in path.split("/") if not s.startswith("<")][-1]
        ctx = (members, texts, readers, parent)
        lists = [("snapy", _STR.findall(args[2]))]
        if len(args) >= 5:
            lists.append((_STR.findall(args[3])[0], _STR.findall(args[4])))
        for reader, keys in lists:
            for k in keys:
                full = f"{path}/{k}"
                rec = {"path": path, "key": k, "reader": reader, "check": f"{rel}:{_line(text, pos)}"}
                if reader != "snapy":
                    rec["default"] = {"kind": "library", "value": "", "file": rel, "line": _line(text, pos)}
                elif full in paths or any(p.startswith(full + "/") for p in paths):
                    rec["default"] = {"kind": "block", "value": "", "file": rel, "line": _line(text, pos)}
                else:
                    rec["default"] = _default(k, args[0], body, start, text, rel, ctx)
                    # a placeholder block (`forcing/diffusion/<key>`) is this key when the parser reads it as a
                    # node, not as a value: no scalar fallback for it
                    d = rec["default"]
                    if any(_matches(p, full) for p in paths) and (
                            d["kind"] in ("none", "guarded", "unread") or re.search(r"[(:{]", d["value"])):
                        rec["default"] = {"kind": "block", "value": "", "file": rel, "line": _line(text, pos)}
                if not rec["default"]["line"]:  # no read found: point at the list that accepts the key
                    rec["default"].update(file=rel, line=_line(text, pos))
                rows.append(rec)
    return rows


def refresh(checkout: Path | None) -> int:
    import code_anchors
    repo, sha = code_anchors.read_pin(REPORT / "code_pin.yml")
    if checkout is None:
        tree = code_anchors.checkout(repo, sha)
    else:
        head = subprocess.run(["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True)
        if head.stdout.strip() != sha:
            print(f"{checkout} is at {head.stdout.strip() or '?'}, not the code pin {sha}")
            return 1
        tree = checkout
    rows = extract(tree)
    DATA.write_text(json.dumps({"repo": repo, "sha": sha, "keys": rows}, indent=1) + "\n")
    print(f"wrote {DATA.relative_to(REPORT)}: {len(rows)} keys at {repo}@{sha[:12]}")
    return 0


# --- the book's sections ----------------------------------------------------------------------------------------

_INCLUDE = re.compile(r"^\{\{<\s*include\s+(\S+)\s*>\}\}\s*$")
_HEAD = re.compile(r"^(#{1,2}) (.*?)\s*$")
_SECTION_FILES = re.compile(r"^chapters/(?:(?:0[1-9]|1[0-6])-|app[de]-)")


def _lines(q: Path, seen: set) -> list[str]:
    if q in seen or not q.exists():
        return []
    seen.add(q)
    out = []
    for line in q.read_text(encoding="utf-8").splitlines():
        m = _INCLUDE.match(line.strip())
        out += _lines((q.parent / m[1]).resolve(), seen) if m else [line]
    return out


def _spans(line: str) -> list[str]:
    """Inline-code names of a line: comma lists split, a trailing `: value` dropped."""
    out = []
    for span in re.findall(r"`([^`\n]+)`", line):
        for part in span.split(","):
            part = part.split(":", 1)[0].strip()
            if part:
                out.append(part)
    return out


def _yaml_paths(lines: list[str]) -> list[str]:
    """Key paths of a fenced YAML example (`forcing:` / `  const-gravity:` / `    grav1: -9.8` gives
    `forcing`, `forcing/const-gravity`, `forcing/const-gravity/grav1`)."""
    out, stack = [], []
    for line in lines:
        m = re.match(r"^(\s*)(?:-\s+)?([\w-]+):", line.split(" #", 1)[0])
        if not m:
            continue
        depth = len(m[1])
        stack = [(d, k) for d, k in stack if d < depth] + [(depth, m[2])]
        out.append("/".join(k for _, k in stack))
    return out


def sections(book: Path) -> list[tuple[str, str, list[str]]]:
    """(label, title, inline-code names and YAML example paths) of every labelled `##` section that may explain
    a key: chapters 1 to 16 and appendices D and E, in book order."""
    import gen_topic_index as topics
    cfg = (book / "_quarto.yml").read_text()
    listed = re.findall(r"^\s*-\s+(chapters/\S+\.qmd)\s*$", cfg, re.M)
    out, seen = [], set()
    for rel in listed:
        if not _SECTION_FILES.match(rel):
            continue
        cur, fence, yaml, comment = None, False, None, False
        for line in _lines((book / rel).resolve(), seen):
            if line.lstrip().startswith("```"):
                if fence and yaml is not None and cur:
                    cur[2] += _yaml_paths(yaml)
                fence = not fence
                yaml = [] if fence and line.strip() in ("```yaml", "```yml") else None
                continue
            if fence:
                if yaml is not None:
                    yaml.append(line)
                continue
            if comment or "<!--" in line:
                comment = "-->" not in (line.split("<!--", 1)[1] if "<!--" in line else line)
                continue
            m = _HEAD.match(line)
            if m:
                lab = re.search(r"\{[^}]*#(sec-[\w-]+)[^}]*\}\s*$", m[2])
                cur = [lab[1], topics.plain_title(re.sub(r"\s*\{[^}]*\}\s*$", "", m[2])), []] \
                    if lab and len(m[1]) == 2 else None
                if cur:
                    out.append(cur)
                continue
            if cur:
                cur[2] += _spans(line)
    return [(lab, title, spans) for lab, title, spans in out]


def defining_sections(report: Path = REPORT) -> dict[str, str]:
    """YAML key -> the section that tools/reader-glossary.json says defines it (entries not marked not-defined-here)."""
    path = report / "tools" / "reader-glossary.json"
    if not path.exists():
        return {}
    return {e["term"]: e["section"] for e in json.loads(path.read_text())["entries"]
            if e.get("kind") == "key" and not e.get("not_defined_here") and e.get("section")}


def explaining(row: dict, secs, defining: dict[str, str] = {}, unique: set[str] = frozenset()) -> tuple[str, str] | None:
    """The section that names the key: path matches first, then the glossary's defining section, then the most
    mentions, then book order. A bare key counts in a section that also names one of its enclosing blocks, or
    anywhere when no other block accepts a key of that name (names of five or more letters, or with `-` or `_`)."""
    path = [s for s in row["path"].split("/") if not s.startswith("<")]
    key, parent = row["key"], path[-1]
    full, tail = "/".join(path + [key]), f"{parent}/{key}"
    best = None
    for n, (lab, title, spans) in enumerate(secs):
        strong = sum(1 for s in spans if s == full or s.endswith("/" + tail) or s == tail
                     or s.startswith(full + "/"))
        has_block = key in unique or any(s == b or f"/{b}/" in f"/{s}/" for s in spans for b in path)
        weak = sum(1 for s in spans if s == key) if has_block else 0
        if not (strong or weak):
            continue
        score = (1 if strong else 0, 1 if defining.get(key) == lab else 0, strong + weak, -n)
        if best is None or score > best[0]:
            best = (score, lab, title)
    return (best[1], best[2]) if best else None


# --- the fragment -----------------------------------------------------------------------------------------------

def _cell_default(d: dict) -> str:
    kind, value = d["kind"], d["value"]
    if kind == "fallback":
        variable = re.fullmatch(r"[a-z_]\w*", value) and value not in ("true", "false")
        return f"`{value}`" + (" (a variable of the parser)" if variable else "")
    if kind == "struct":
        return f"`{value}` (options struct)"
    return {"block": "block", "required": "required", "library": "—", "guarded": "none (read only when present)",
            "map": "none (a map, iterated)", "unread": "accepted, not read", "none": "no fallback found"}[kind]


def _link(repo: str, sha: str, f: str, line: int) -> str:
    return f"[`{f}:{line}`](https://github.com/{repo}/blob/{sha}/{f}#L{line})" if line else f"`{f}`"


def render(data: dict, secs, defining: dict[str, str] = {}) -> tuple[str, dict]:
    repo, sha = data["repo"], data["sha"]
    rows = data["keys"]
    names = [r["key"] for r in rows]
    unique = {k for k in names if names.count(k) == 1 and re.search(r"[-_]|^\w{5,}$", k)}
    linked = {i: explaining(r, secs, defining, unique) for i, r in enumerate(rows)}
    blocks: dict[str, list[int]] = {}
    for i, r in enumerate(rows):
        blocks.setdefault(r["path"].split("/")[0], []).append(i)
    stats = {"keys": len(rows), "blocks": len({r["path"] for r in rows}),
             "snapy": sum(r["reader"] == "snapy" for r in rows),
             "library": sum(r["reader"] != "snapy" for r in rows),
             "linked": sum(1 for v in linked.values() if v), "unlinked": sum(1 for v in linked.values() if not v),
             "sections": len({v[0] for v in linked.values() if v})}
    for kind in ("fallback", "struct", "block", "required", "guarded", "map", "unread", "library", "none"):
        stats["default_" + kind] = sum(r["default"]["kind"] == kind for r in rows)
    out = [HEADER, "",
           f"{stats['keys']} keys in {stats['blocks']} checked blocks at "
           f"[`{sha}`](https://github.com/{repo}/commit/{sha}): {stats['snapy']} read by snapy, "
           f"{stats['library']} accepted in a shared block and read by kintera or pyharp. "
           f"{stats['linked']} keys are named by a section of the book, in {stats['sections']} sections; "
           f"{stats['unlinked']} are named by none (\"no section\").", ""]
    for top, idx in sorted(blocks.items()):
        out += [f"### `{top}`", "", "| key | default | read at | explained in |", "|---|---|---|---|"]
        for i in sorted(idx, key=lambda i: (rows[i]["path"], rows[i]["reader"] != "snapy", rows[i]["key"])):
            r, d = rows[i], rows[i]["default"]
            key = f"`{r['path']}/{r['key']}`"
            where = _link(repo, sha, d["file"], d["line"])
            if r["reader"] != "snapy":
                where = f"{r['reader']} (listed at {_link(repo, sha, *r['check'].split(':')[:1], int(r['check'].split(':')[1]))})"
            sec = linked[i]
            out.append(f"| {key} | {_cell_default(d)} | {where} | {'@' + sec[0] if sec else 'no section'} |")
        out += ["", f": Keys of the `{top}` block{'s' if len({rows[i]['path'] for i in idx}) > 1 else ''}. "
                    f"{{#tbl-appi-{re.sub(r'[^a-z0-9]+', '-', top)}}}", ""]
    return "\n".join(out).rstrip() + "\n", stats


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--refresh", nargs="?", const="", metavar="CHECKOUT")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stats", action="store_true")
    ap.add_argument("--book", type=Path, default=BOOK)
    ns = ap.parse_args(argv)
    if ns.refresh is not None:
        rc = refresh(Path(ns.refresh) if ns.refresh else None)
        if rc:
            return rc
    data = json.loads(DATA.read_text())
    text, stats = render(data, sections(ns.book), defining_sections(ns.book.resolve().parent))
    if ns.stats:
        print(json.dumps(stats, indent=1))
    fragment = ns.book / "chapters" / "17-appendices" / FRAGMENT.name
    if ns.check:
        if not fragment.exists() or fragment.read_text() != text:
            print(f"{fragment}: stale; run python3 tools/gen_deck_keys.py")
            return 1
        print(f"deck keys: fragment current ({stats['keys']} keys, {stats['linked']} linked)")
        return 0
    fragment.write_text(text)
    print(f"wrote {fragment.relative_to(ns.book.parent)}: {stats['keys']} keys, {stats['linked']} linked, "
          f"{stats['unlinked']} with no section")
    return 0


