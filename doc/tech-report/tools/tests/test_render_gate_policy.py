"""Tests of the report-only policy of tools/render_gate.py and of the generated setup notes.

The policy decides which gate failures are reported rather than failed. It used to live twice --
once in the render workflow, once nowhere locally -- so a fresh clone exited 1 on gates CI was
green on. These tests pin the rule itself, so the two consumers of
`tools/render-gate-policy.json` cannot drift apart again.

Run from the report directory: `python3 -m pytest tools/tests`.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

TOOLS = Path(__file__).resolve().parent.parent
REPORT = TOOLS.parent
sys.path.insert(0, str(TOOLS))

import render_gate  # noqa: E402

POLICY = render_gate.load_policy()
OVERFULL = "overfull box > 10 pt"


def test_policy_file_is_the_one_the_gate_reads():
    raw = json.loads((TOOLS / "render-gate-policy.json").read_text())
    assert set(raw["report_only_gates"]) == set(POLICY[0])
    assert set(raw["report_only_log_items"]) == set(POLICY[1])
    assert raw["report_only_gates"], "a policy that tolerates no gate would fail every fresh clone"


@pytest.mark.parametrize("status, failed, log_items, expected", [
    (0, [], set(), 0),                                    # clean
    (render_gate.PENDING_EXIT, [], set(), render_gate.PENDING_EXIT),  # pending keeps its status
    (1, ["freeze tracked"], set(), 0),                    # the gate a fresh clone can never pass
    (1, ["freeze tracked", "log"], {OVERFULL}, 0),        # what a fresh clone actually reports
    (1, ["log"], {OVERFULL}, 0),                          # typography alone
    (1, ["log"], {OVERFULL, "missing character"}, 1),     # one unlisted item fails the log gate
    (1, ["log"], set(), 1),                               # the log gate was blind: not tolerated
    (1, ["freeze tracked", "provenance"], {OVERFULL}, 1),  # a real gate alongside a tolerated one
    (1, [], set(), 1),                                    # only the gate's expected failures
])
def test_apply_policy(status, failed, log_items, expected):
    assert render_gate.apply_policy(status, failed, log_items, POLICY)[0] == expected


def test_a_missing_policy_file_tolerates_nothing(tmp_path):
    assert render_gate.load_policy(tmp_path / "absent.json") == (frozenset(), frozenset())
    assert render_gate.apply_policy(1, ["freeze tracked"], set(),
                                    (frozenset(), frozenset()))[0] == 1


def test_strict_keeps_the_untreated_verdict():
    """--strict must still fail, or the policy could not be audited from the same command."""
    results = {"freeze tracked": "fail"}
    assert render_gate._verdict(dict(results), release=False, policy=None) == 1
    assert render_gate._verdict(dict(results), release=False,
                                log_items=frozenset(), policy=POLICY) == 0


def test_the_workflow_states_no_policy_of_its_own():
    """CI must judge the run by the gate's exit code, not by a second copy of the rule."""
    workflow = (REPORT.parent.parent / ".github/workflows/tech-report.yml").read_text()
    assert "REPORT_ONLY_GATES" not in workflow
    assert "REPORT_ONLY_LOG_ITEMS" not in workflow
    assert "render-gate-policy.json" in workflow


def test_setup_notes_block_matches_this_environment():
    """The generated rows of SETUP.md are measured, not typed; anything unmeasurable is skipped."""
    proc = subprocess.run([sys.executable, str(TOOLS / "setup_notes.py"), "--check"],
                          capture_output=True, text=True, cwd=REPORT, timeout=1800)
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_setup_notes_rows_carry_no_typed_duplicate():
    """A measured number must live in the generated block and nowhere else in the notes."""
    text = (REPORT / "SETUP.md").read_text()
    before, rest = text.split("<!-- generated by tools/setup_notes.py", 1)
    block, after = rest.split("<!-- end generated -->", 1)
    counts = re.findall(r"(\d+) citations, (\d+) distinct", block)
    assert counts, "the citation row left the generated block"
    outside = before + after
    for found, distinct in counts:
        assert f"{found} citations" not in outside
        assert f"{distinct} distinct" not in outside
