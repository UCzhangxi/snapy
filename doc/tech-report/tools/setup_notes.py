#!/usr/bin/env python3
"""Keep the measured lines of SETUP.md measured, instead of typed.

Two rows of the "What was and was not verified" table carry numbers that a run produces: the
versions `setup.sh --with-native` installs, and the counts the code-citation check prints. Typed by
hand, they drifted -- the notes claimed a pyharp version the pinned commit does not install, and a
citation count that no longer matched. Nothing compared either against a run, so nothing noticed.

    python3 tools/setup_notes.py --write    # rewrite the generated block from this environment
    python3 tools/setup_notes.py --check    # fail if the committed block disagrees with it

`--check` compares only what the current environment can answer: an uninstalled package is skipped
and said so, rather than guessed. In a plain checkout that leaves the citation counts, which need no
build; after `setup.sh --with-native` it covers the versions too. Exit 1 on any disagreement.
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
NOTES = HERE.parent / "SETUP.md"
BEGIN = "<!-- generated by tools/setup_notes.py --write; do not edit by hand -->"
END = "<!-- end generated -->"

#: The packages the native row names, in the order it names them.
PACKAGES = ("pydisort", "pyharp", "kintera", "pinc", "snapy", "torch")


def installed_versions() -> dict[str, str | None]:
    """The version of each package, or None when it is not installed here.

    torch is read from the module, not from the distribution metadata, because only the module
    carries the build tag (`+cu128`, `+cpu`), and which build is installed is the point of the row.
    """
    out: dict[str, str | None] = {}
    for name in PACKAGES:
        try:
            out[name] = md.version(name)
        except md.PackageNotFoundError:
            out[name] = None
    if out.get("torch"):
        try:
            import torch
            out["torch"] = str(torch.__version__)
        except ImportError:
            pass
    return out


def netcdf_version(prefix: pathlib.Path | None = None) -> str | None:
    """netCDF's own `nc-config --version`, from the prefix setup.sh builds it into."""
    candidates = []
    if prefix:
        candidates.append(prefix / "netcdf/bin/nc-config")
    candidates.append(HERE.parent / ".report-env/netcdf/bin/nc-config")
    for nc in candidates:
        if nc.exists():
            try:
                text = subprocess.run([str(nc), "--version"], capture_output=True, text=True,
                                      timeout=60).stdout
            except (OSError, subprocess.SubprocessError):
                continue
            if m := re.search(r"([0-9]+\.[0-9]+\.[0-9]+)", text):
                return m.group(1)
    return None


def citation_counts() -> tuple[int, int, int] | None:
    """(found, distinct, unresolved) from the citation check's own line, or None if it cannot run."""
    try:
        proc = subprocess.run([sys.executable, str(HERE / "code_anchors.py"), "check"],
                              capture_output=True, text=True, cwd=HERE.parent, timeout=1800)
    except (OSError, subprocess.SubprocessError):
        return None
    m = re.search(r"code citations: (\d+) found, (\d+) distinct resolved at \S+, (\d+) unresolved",
                  proc.stdout + proc.stderr)
    return (int(m.group(1)), int(m.group(2)), int(m.group(3))) if m else None


def render(versions, netcdf, counts) -> list[str]:
    """The generated rows. A value this environment cannot produce keeps the committed one."""
    rows = []
    # All of them or none: a plain setup installs netCDF and torch but not the native stack, and a
    # row naming two of seven packages would read as a measurement of the other five.
    if all(versions.get(n) for n in PACKAGES) and netcdf:
        named = ", ".join(f"{n} {versions[n]}" for n in PACKAGES)
        rows.append(f"| `bash setup.sh --with-native` | exit 0; {named}, netCDF {netcdf} |")
    if counts:
        rows.append(f"| `python3 tools/code_anchors.py check` | {counts[0]} citations, "
                    f"{counts[1]} distinct, {counts[2]} unresolved |")
    return rows


def committed_block(text: str) -> list[str]:
    if BEGIN not in text or END not in text:
        sys.exit(f"setup_notes.py: {NOTES} has no generated block; add the {BEGIN} / {END} markers")
    body = text.split(BEGIN, 1)[1].split(END, 1)[0]
    return [l for l in body.splitlines() if l.strip()]


def replace_block(text: str, rows: list[str]) -> str:
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + BEGIN + "\n" + "\n".join(rows) + "\n" + END + tail


def key(row: str) -> str:
    return row.split("|")[1].strip() if row.count("|") > 1 else row.strip()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite the block from this environment")
    mode.add_argument("--check", action="store_true", help="fail if the committed block disagrees")
    ap.add_argument("--prefix", type=pathlib.Path, default=None, help="where setup.sh installed")
    args = ap.parse_args(argv)

    versions = installed_versions()
    netcdf = netcdf_version(args.prefix)
    counts = citation_counts()
    measured = {key(r): r for r in render(versions, netcdf, counts)}
    text = NOTES.read_text()
    committed = {key(r): r for r in committed_block(text)}

    if args.write:
        rows = [measured.get(k, committed[k]) for k in committed] \
            + [r for k, r in measured.items() if k not in committed]
        NOTES.write_text(replace_block(text, rows))
        for k in committed:
            if k not in measured:
                print(f"  kept (this environment cannot measure it): {k}")
        print(f"setup_notes.py: wrote {len(rows)} row(s) into {NOTES.name}")
        return 0

    skipped = [k for k in committed if k not in measured]
    bad = [(k, committed[k], measured[k]) for k in committed if k in measured
           and committed[k].strip() != measured[k].strip()]
    for k in skipped:
        print(f"  skipped, not measurable here: {k}")
    missing = [n for n in PACKAGES if not versions.get(n)]
    if missing:
        print(f"  not installed here: {', '.join(missing)}")
    for k, was, now in bad:
        print(f"  ✗ {k}\n      committed: {was.strip()}\n      measured:  {now.strip()}")
    if bad:
        print(f"setup_notes.py: {len(bad)} generated row(s) disagree with this run; "
              "re-run with --write")
        return 1
    print(f"setup_notes.py: {len(committed) - len(skipped)} of {len(committed)} generated row(s) "
          f"match this run, {len(skipped)} not measurable here")
    return 0


if __name__ == "__main__":
    sys.exit(main())
