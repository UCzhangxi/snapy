#!/usr/bin/env python3
"""One-time conversion of the line-number code links of the book to symbol citations (tools/code_anchors.py).

Each snapy link `[`basename:a-b`](https://github.com/chengcli/snapy/blob/<sha>/<path>#La-Lb)` is resolved at its
own sha: the smallest symbol whose lines contain a..b becomes `{{< code <path> <symbol> >}}`, provided that the
citation also resolves at the pin. Nothing else in a line changes. A link that cannot be mapped (other
repository, link text that is not `basename:lines`, lines outside any one symbol, a symbol gone at the pin,
a generated file) is left as it is and listed, with the reason, in reviews/code-anchors-unmapped.tsv.

    python3 tools/convert_code_links.py convert [--dry-run]
    python3 tools/convert_code_links.py verify <rev>   # the oracle: every converted link, against the book at <rev>;
                                                       # lists in reviews/code-anchors-reread.tsv those whose
                                                       # symbol changed between the link's sha and the pin
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from code_anchors import (BOOK, REPORT, SHORTCODE, Cite, Snapshot, Unresolved, book_files,  # noqa: E402
                          parse_args, read_pin)

UNMAPPED = REPORT / "reviews" / "code-anchors-unmapped.tsv"
REREAD = REPORT / "reviews" / "code-anchors-reread.tsv"
LINK = re.compile(r"\[`(?P<text>[^`\]]+)`\]\((?P<url>https://github\.com/(?P<repo>[\w.-]+/[\w.-]+)/blob/"
                  r"(?P<sha>[0-9a-f]{40})/(?P<path>[^)#\s]+)(?:#L(?P<a>\d+)(?:-L(?P<b>\d+))?)?)\)")
# written by a generator from its own inputs; converting them by hand would not survive the next generation
GENERATED = {"_appc-test-index.qmd": "generated by tools/gen_test_index.py",
             "_appb-derivation-index.qmd": "generated by tools/gen_derivation_index.py",
             "_appa-notation.qmd": "generated by tools/gen_notation_index.py"}


def _fences(lines: list[str]) -> list[bool]:
    inside, out = False, []
    for line in lines:
        if line.lstrip().startswith(("```", "~~~")):
            inside = not inside
            out.append(True)
        else:
            out.append(inside)
    return out


def cited_lines(m: re.Match) -> tuple[int, int]:
    """The link's lines at its own sha, without blank lines at either end (they carry no claim)."""
    a, b = int(m["a"]), int(m["b"] or m["a"])
    text = Snapshot.of(m["repo"], m["sha"]).lines(m["path"], a, b)
    while a < b and not text[0].strip():
        a, text = a + 1, text[1:]
    while b > a and not text[-1].strip():
        b, text = b - 1, text[:-1]
    return a, b


def map_link(m: re.Match, pin: Snapshot) -> Cite | str:
    """The citation for one link, or the reason it cannot be mapped."""
    if m["repo"] != pin.repo:
        return f"repository {m['repo']} has no code pin"
    path, text = m["path"], m["text"]
    a, b = (int(m["a"]), int(m["b"] or m["a"])) if m["a"] else (None, None)
    want = f":{a}-{b}" if b != a else f":{a}" if a else ""
    if not (text.endswith(want) and ("/" + path).endswith("/" + text[:len(text) - len(want)])):
        return "link text is not basename:lines of its URL"
    origin = Snapshot.of(m["repo"], m["sha"])
    if m["path"] not in origin.files:
        return f"no file {path} at {m['sha'][:9]}"
    if a is not None:
        a, b = cited_lines(m)
    if a is None:
        cite = Cite(path, None, None)
    else:
        around = [s for s in origin.symbols(path) if s.start <= a and b <= s.end]
        if not around:
            inside = [s for s in origin.symbols(path) if a <= s.end and s.start <= b]
            return "lines span several symbols" if inside else "lines outside any symbol"
        best = min(around, key=lambda s: (s.end - s.start, s.kind == "prototype"))
        cite = Cite(path, best.name, None)
        try:
            origin.resolve(cite)
        except Unresolved:  # ambiguous: name its overload, counted in file order
            same = sorted((s for s in origin.symbols(path) if s.name == best.name), key=lambda s: s.start)
            cite = Cite(path, best.name, same.index(best) + 1)
        rng = origin.resolve(cite)
        if not (rng[0] <= a and b <= rng[1]):
            return f"{cite.shortcode()} does not cover the lines at {m['sha'][:9]}"
    try:
        rng = pin.resolve(cite)
    except Unresolved as e:
        return f"at the pin: {e}"
    if cite.overload:  # the same overload at the pin: same kind and signature
        sig = lambda snap, r: {(s.kind, s.signature) for s in snap.symbols(path)  # noqa: E731
                               if s.name == cite.symbol and (s.start, s.end) == r}
        if sig(origin, origin.resolve(cite)) != sig(pin, rng):
            return f"overload={cite.overload} is a different overload at the pin"
    return cite


def cmd_convert(dry: bool) -> int:
    repo, sha = read_pin()
    pin = Snapshot.of(repo, sha)
    rows, done, total = [], 0, 0
    for f in book_files():
        lines = f.read_text().split("\n")
        fenced = _fences(lines)
        changed = False
        for n, line in enumerate(lines):
            def sub(m: re.Match) -> str:
                nonlocal done, total
                total += 1
                if f.name in GENERATED:
                    why = GENERATED[f.name]
                elif fenced[n]:
                    why = "inside a code block"
                else:
                    why = map_link(m, pin)
                if isinstance(why, Cite):
                    done += 1
                    return why.shortcode()
                rows.append(f"{f.relative_to(BOOK)}\t{n + 1}\t{why}\t{m.group(0)}")
                return m.group(0)
            new = LINK.sub(sub, line)
            if new != line:
                lines[n], changed = new, True
        if changed and not dry:
            f.write_text("\n".join(lines))
    if not dry:
        UNMAPPED.write_text("file\tline\treason\tlink\n" + "\n".join(rows) + "\n")
    print(f"code links: {total} total, {done} converted, {len(rows)} unmapped"
          f" ({'dry run' if dry else UNMAPPED.relative_to(REPORT)})")
    reasons: dict[str, int] = {}
    for r in rows:
        k = re.sub(r"\{\{<.*?>\}\}|no symbol \S+ in \S+|no file \S+", "…", r.split("\t")[2])
        reasons[k] = reasons.get(k, 0) + 1
    for k, v in sorted(reasons.items(), key=lambda kv: -kv[1]):
        print(f"  {v:5d}  {k}")
    return 0


def cmd_verify(rev: str) -> int:
    """Each file is its text at `rev` with only links replaced by shortcodes, and each shortcode resolves, at its
    link's own sha, to lines that contain the link's lines; its symbol is named in those lines."""
    repo, sha = read_pin()
    pin = Snapshot.of(repo, sha)
    top = Path(subprocess.run(["git", "-C", str(REPORT), "rev-parse", "--show-toplevel"], capture_output=True,
                              text=True, check=True).stdout.strip())
    checked = passed = kept = 0
    fails, reread = [], []
    for f in book_files():
        if f.name in GENERATED:  # regenerated by its generator, whose --check covers it
            continue
        old = subprocess.run(["git", "-C", str(top), "show", f"{rev}:{f.relative_to(top)}"], capture_output=True,
                             text=True)
        if old.returncode != 0:
            continue
        old, new = old.stdout, f.read_text()
        pos = 0
        pieces, last = [], 0
        for m in LINK.finditer(old):
            pieces.append((old[last:m.start()], m))
            last = m.end()
        tail = old[last:]
        ok_file = True
        for prose, m in pieces:
            if not new.startswith(prose, pos):
                ok_file = False
                break
            pos += len(prose)
            if new.startswith(m.group(0), pos):
                pos += len(m.group(0))
                kept += 1
                continue
            s = SHORTCODE.match(new, pos)
            if not s:
                ok_file = False
                break
            pos = s.end()
            checked += 1
            cite = parse_args(s.group("args"))
            try:
                if cite.path != m["path"]:
                    raise Unresolved("path differs from the link's")
                origin = Snapshot.of(m["repo"], m["sha"])
                rng = origin.resolve(cite)
                pin.resolve(cite)
                if m["a"]:
                    a, b = cited_lines(m)
                    if not (rng[0] <= a and b <= rng[1]):
                        raise Unresolved(f"L{rng[0]}-L{rng[1]} at {m['sha'][:9]} misses L{a}-L{b}")
                    leaf = re.split(r"::|\.", cite.symbol)[-1]
                    head = "\n".join(origin.lines(cite.path, *rng))
                    if not re.search(rf"\b{re.escape(leaf)}\b", head):
                        raise Unresolved(f"{leaf} not named in L{rng[0]}-L{rng[1]} at {m['sha'][:9]}")
                passed += 1
                now = pin.resolve(cite)
                body = (lambda snap, r: snap.lines(cite.path, *r) if r else
                        (snap.tree / cite.path).read_text(errors="replace").splitlines())
                if body(origin, rng) != body(pin, now):
                    where = f"L{rng[0]}-L{rng[1]} -> L{now[0]}-L{now[1]}" if rng else "file"
                    reread.append(f"{f.relative_to(BOOK)}\t{new.count(chr(10), 0, pos) + 1}\t{m['sha'][:9]}"
                                  f"\t{s.group(0)}\t{where}")
            except Unresolved as e:
                fails.append(f"{f.relative_to(BOOK)}: {s.group(0)}: {e}")
        if not ok_file or new[pos:] != tail:
            fails.append(f"{f.relative_to(BOOK)}: text outside the citations differs from {rev}")
    for x in fails:
        print(x)
    REREAD.write_text("file\tline\tlink sha\tcitation\tlines (link sha -> pin)\n" + "\n".join(reread) + "\n")
    print(f"{len(reread)} converted citations whose symbol changed between the link's sha and the pin:"
          f" {REREAD.relative_to(REPORT)} (re-read them)")
    print(f"verify against {rev}: {checked} converted checked, {passed} passed; {kept} links kept;"
          f" {checked + kept} total")
    return 1 if fails else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("convert")
    p.add_argument("--dry-run", action="store_true")
    p = sub.add_parser("verify")
    p.add_argument("rev")
    ns = ap.parse_args()
    return cmd_convert(ns.dry_run) if ns.cmd == "convert" else cmd_verify(ns.rev)


if __name__ == "__main__":
    sys.exit(main())
